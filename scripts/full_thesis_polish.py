def delete_paragraph(paragraph) -> None:
    element = paragraph._element
    parent = element.getparent()
    if parent is not None:
        parent.remove(element)
    paragraph._p = paragraph._element = None


def insert_before(paragraph, text: str, style=None) -> Paragraph:
    new_p = OxmlElement("w:p")
    paragraph._p.addprevious(new_p)
    new_para = Paragraph(new_p, paragraph._parent)
    new_para.text = text
    if style is not None:
        new_para.style = style
    return new_para


def paragraph_exists(doc: Document, text: str) -> bool:
    return any(p.text.strip() == text for p in doc.paragraphs)


def add_missing_chapter_headings(doc: Document) -> int:
    chapter_style = None
    for p in doc.paragraphs:
        if p.text.strip().startswith("第 1 章"):
            chapter_style = p.style
            break

    inserted = 0
    for target, chapter in CHAPTER_HEADINGS:
        if paragraph_exists(doc, chapter):
            continue
        for p in doc.paragraphs:
            if p.text.strip() == target:
                insert_before(p, chapter, chapter_style)
                inserted += 1
                break
    return inserted


def main() -> None:
    if not DOCX_PATH.exists():
        raise FileNotFoundError(DOCX_PATH)

    backup = DOCX_PATH.with_name(
        f"{DOCX_PATH.stem}-before-full-polish-run-{datetime.now().strftime('%Y%m%d-%H%M%S')}{DOCX_PATH.suffix}"
    )
    shutil.copy2(DOCX_PATH, backup)

    doc = Document(DOCX_PATH)
    inserted = add_missing_chapter_headings(doc)

    replaced = 0
    cleaned = 0
    removed = 0
    for p in list(doc.paragraphs):
        text = p.text.strip()
        if text in REMOVE_STANDALONE:
            delete_paragraph(p)
            removed += 1
            continue
        if text in REPLACEMENTS:
            p.text = REPLACEMENTS[text]
            replaced += 1
            continue
        new_text = p.text
        for old, new in INLINE_CLEANUPS.items():
            if old in new_text:
                new_text = new_text.replace(old, new).strip()
        if new_text != p.text:
            p.text = new_text
            cleaned += 1

    doc.save(DOCX_PATH)

    report = Path("output/论文全文润色报告.md")
    report.write_text(
        "# 论文全文润色报告\n\n"
        f"- 论文文件：`{DOCX_PATH.as_posix()}`\n"
        f"- 备份文件：`{backup.as_posix()}`\n"
        f"- 新增缺失章标题数量：{inserted}\n"
        f"- 段落级润色替换数量：{replaced}\n"
        f"- 内联图题/表题清理数量：{cleaned}\n"
        f"- 删除孤立占位段落数量：{removed}\n\n"
        "## 润色原则\n\n"
        "- 保留系统真实功能、真实实验数据和已有图片表格。\n"
        "- 减少模板化、空泛化表述，增强字段、接口、合约方法和实验过程等工程细节。\n"
        "- 修正章节顺序、截断句、残留图题和明显格式硬伤。\n"
        "- 不新增未提供的实验数据、功能或参考文献。\n",
        encoding="utf-8",
    )
    print(report.as_posix())
    print(f"backup={backup.as_posix()}")
    print(f"inserted_chapters={inserted}")
    print(f"replaced={replaced}")
    print(f"cleaned={cleaned}")
    print(f"removed={removed}")


if __name__ == "__main__":
    main()
