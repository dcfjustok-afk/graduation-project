def set_cell_text(table, row: int, col: int, text: str) -> None:
    cell = table.Cell(row, col)
    rng = cell.Range
    rng.End = rng.End - 1
    rng.Text = text


def generate() -> None:
    template = RECORD_DIR / TEMPLATE_NAME
    if not template.exists():
        raise FileNotFoundError(template)

    temp_template = RECORD_DIR / TEMP_TEMPLATE_NAME
    shutil.copyfile(template, temp_template)

    word = win32com.client.DispatchEx("Word.Application")
    word.Visible = False
    word.DisplayAlerts = 0

    try:
        for item in WEEKS:
            output = RECORD_DIR / f"第{item['week']}周记录本.docx"
            if output.exists():
                output.unlink()

            doc = word.Documents.Open(str(temp_template), False, False)
            try:
                table = doc.Tables(1)
                set_cell_text(table, 1, 2, f"第{item['week']}周（{item['range']}）")
                set_cell_text(table, 1, 4, STUDENT)
                set_cell_text(table, 1, 6, LOCATION)
                set_cell_text(table, 2, 2, item["done"])
                set_cell_text(table, 3, 2, item["next"])
                doc.SaveAs2(str(output), FileFormat=16)
            finally:
                doc.Close(False)
    finally:
        word.Quit()
        if temp_template.exists():
            temp_template.unlink()


if __name__ == "__main__":
    generate()
